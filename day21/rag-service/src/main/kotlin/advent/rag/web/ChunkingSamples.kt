Работа начинается с индексации. Документы разбивают на чанки — куски текста, которые помещаются в контекст модели эмбеддингов. Для каждого чанка считают эмбеддинг: вектор из сотен чисел, в котором близкие по смыслу тексты оказываются рядом. Векторы вместе с метаданными — откуда чанк, из какого раздела — сохраняют в индекс.

Когда пользователь задаёт вопрос, его тоже превращают в вектор и ищут в индексе самые похожие чанки, обычно по косинусному сходству. Найденные фрагменты добавляют в промпт как контекст, и генеративная модель формулирует ответ, опираясь на них.

