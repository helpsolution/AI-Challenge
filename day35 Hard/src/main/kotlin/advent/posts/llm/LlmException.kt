package advent.posts.llm

/**
 * Ошибка обращения к LLM-провайдеру: сеть, таймаут, ответ с кодом не 2xx или пустой результат.
 *
 * Сырое тело ответа носим с собой намеренно: в нем провайдер пишет настоящую причину отказа
 * (баланс, лимит, неверный параметр), поэтому оно доходит до интерфейса дословно.
 */
class LlmException(
    message: String,
    /** Код ответа провайдера, если ответ был. */
    val providerStatus: Int? = null,
    /** Тело ответа провайдера как есть. Ключа в нём нет: ключ уходит заголовком. */
    val providerBody: String? = null,
    cause: Throwable? = null,
) : RuntimeException(message, cause)
