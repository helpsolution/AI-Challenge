package advent.day10.context

import advent.day10.chat.Message
import advent.day10.chat.Session
import advent.day10.chat.Upkeep
import advent.day10.chat.StrategyId
import advent.day10.llm.ApiMessage

/**
 * Граница между «что помним» и «что отправляем» — главная сущность этого дня.
 *
 * Стратегия целиком владеет промптом: персона, история, дополнительные блоки, новый
 * вопрос. Агент в сборку не вмешивается, потому что как только он начнёт что-то
 * дописывать «для всех стратегий», это перестанет быть свойством стратегии — и сравнение
 * поедет.
 *
 * Два метода, а не один, ровно по одной причине: стратегия бывает с состоянием.
 * [assemble] отвечает на вопрос «что отправить сейчас», [observe] даёт обновить своё
 * состояние после того, как ход состоялся. Скользящему окну второй метод не нужен —
 * у него реализация по умолчанию пустая. Стратегии фактов он нужен: она обновляет свой
 * блок ключ-значение отдельным обращением к модели, и делать это внутри агента значило бы
 * протащить одну стратегию во все.
 */
interface ContextStrategy {

    val id: StrategyId

    /** Из чего собрать запрос к модели. Вызывается перед каждым ходом. */
    fun assemble(input: StrategyInput): PromptContext

    /**
     * Ход состоялся — можно обновить своё состояние.
     *
     * Вызывается только после удачного хода и уже после записи в хранилище: если модель
     * не ответила, состоянию стратегии меняться не с чего.
     *
     * Возвращает [Upkeep] — что обновление стоило. Не «для полноты»: стратегия фактов
     * обновляет досье вторым обращением к модели, и если этот расход не вернуть наружу,
     * таблица сравнения покажет её дешевле окна, притом что счёт от провайдера скажет
     * обратное. null — стратегия ничего не потратила, как скользящее окно.
     *
     * Бросать исключений отсюда нельзя: ответ модели уже получен, записан и отдан
     * пользователю. Неудачное обслуживание возвращается как [Upkeep] с `error`.
     */
    fun observe(input: StrategyInput, answer: Message): Upkeep? = null
}

/**
 * Всё, что стратегия знает о разговоре.
 *
 * Хранилища разговора здесь нет намеренно: историю стратегия получает готовым списком
 * и не может сходить за перепиской в обход агента. Своё собственное состояние — досье
 * фактов, например — стратегия ведёт сама и через свой узкий контракт; но переписка
 * приходит только отсюда.
 *
 * Граница ровно та, которой не было в дне 9: там сборка контекста умела дописывать
 * в базу конспект, и понять, что именно ушло модели, можно было только прочитав
 * три класса подряд.
 */
data class StrategyInput(
    val session: Session,
    /** Номер текущего хода. Нужен, чтобы состояние стратегии можно было привязать ко времени. */
    val turnNumber: Int,
    /** Системная инструкция. Пустая строка — агент без характера, голая модель. */
    val persona: String,
    /** Вся переписка сессии в порядке диалога: старое → новое. Без нового вопроса. */
    val history: List<Message>,
    /** Новый вопрос пользователя. В [history] его ещё нет. */
    val question: String,
)

/**
 * Собранный промпт и его состав.
 *
 * Блоков недостаточно. Главный вопрос дня — не «что ушло», а «что стратегия выбросила
 * и чем за это заплатила», и отвечает на него только разбор состава. Поэтому
 * [includedMessages] возвращается отдельно от [blocks]: пересчитать по блокам его нельзя,
 * там кроме истории есть и персона, и вопрос, и блоки самой стратегии.
 */
data class PromptContext(
    val blocks: List<ApiMessage>,
    /** Сколько сообщений истории вошло в промпт дословно. */
    val includedMessages: Int,
    /** Чем стратегия дополнила историю: блок фактов, метка ветки. null — ничем. */
    val note: String? = null,
) {
    val charsSent: Int get() = blocks.sumOf { it.content.length }
}
