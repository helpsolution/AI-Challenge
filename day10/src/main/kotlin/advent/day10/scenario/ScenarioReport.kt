package advent.day10.scenario

import advent.day10.chat.StrategyId
import advent.day10.chat.Totals
import com.fasterxml.jackson.annotation.JsonIgnoreProperties
import java.time.Instant

/**
 * Итог одного прогона сценария на одной стратегии.
 *
 * Три группы чисел, и они намеренно не сводятся в одну оценку: «лучшая стратегия» —
 * вопрос без ответа, потому что удержание деталей и расход тянут в разные стороны.
 * Отчёт показывает обе стороны сделки, а выбор оставляет человеку.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
data class ScenarioRun(
    val id: Long,
    val scenarioId: String,
    val scenarioTitle: String,
    val strategy: StrategyId,
    val windowSize: Int,
    /** Сессия, в которой прошёл сценарий. Её можно открыть и прочитать целиком. */
    val sessionId: Long,
    val startedAt: Instant,
    val finishedAt: Instant,
    /**
     * Расход самого сценария: пятнадцать реплик в основной сессии.
     *
     * Только он и сравним между стратегиями — это одинаковая нагрузка, одинаковый вход,
     * одинаковое число ходов.
     */
    val totals: Totals,
    /**
     * Расход контрольных вопросов — цена измерения, а не стратегии.
     *
     * Вынесен отдельно после того, как появилась стратегия фактов. Проверки задаются
     * в ветках, и каждая из них для этой стратегии — не один вызов модели, а два:
     * ответ и обновление досье в ветке, которую тут же выбрасывают. Слей мы это
     * с расходом сценария — и таблица показала бы, что факты дороже окна в том числе
     * на восемь вызовов, которых в настоящей работе агента нет вовсе.
     *
     * null у прогонов, сделанных до этого разделения.
     */
    val probeTotals: Totals? = null,
    val checks: List<CheckResult>,
    /**
     * Прогон не доехал до конца: модель не ответила, кончились деньги, оборвалась сеть.
     *
     * Отчёт всё равно сохраняется — с теми проверками, которые успели пройти. Молча
     * выбросить пятнадцать состоявшихся ходов ради того, чтобы шестнадцатый не испортил
     * картинку, было бы худшим решением: заплатили за них уже.
     */
    val error: String? = null,
) {
    val passed: Int get() = checks.count { it.passed }

    /** Доля пройденных проверок, 0..1. */
    val retention: Double get() = if (checks.isEmpty()) 0.0 else passed.toDouble() / checks.size

    /**
     * Самый ранний шаг, деталь с которого агент ещё помнит.
     *
     * Это и есть граница памяти одним числом. У полного удержания — 1, у стратегии
     * с тесным окном — номер где-то в середине сценария, и он говорит больше, чем
     * доля пройденных проверок.
     */
    val earliestRemembered: Int? get() = checks.filter { it.passed }.minOfOrNull { it.plantedAtStep }
}

/**
 * Результат одной проверки.
 *
 * [sessionId] — не та сессия, в которой шёл сценарий, а ветка от её конца. Каждый
 * контрольный вопрос задаётся в собственной ветке, и это принципиально: спроси их
 * подряд в одной сессии — и к восьмому вопросу окно будет заполнено ответами
 * на первые семь, то есть сам сценарий из него вытеснится. Тогда провалились бы все
 * поздние проверки независимо от стратегии, и разбивка по шагам потеряла бы смысл.
 * Ветка даёт каждому вопросу одинаковый контекст: ровно тот, каким диалог закончился.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
data class CheckResult(
    val id: String,
    val plantedAtStep: Int,
    val question: String,
    val answer: String,
    val passed: Boolean,
    /** Ожидаемые подстроки, которых в ответе не нашлось. */
    val missing: List<String>,
    /** Запрещённые подстроки, которые в ответе нашлись: агент выдумал то, чего не было. */
    val hallucinated: List<String>,
    val sessionId: Long,
)
