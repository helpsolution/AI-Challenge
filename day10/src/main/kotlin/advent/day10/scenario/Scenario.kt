package advent.day10.scenario

/**
 * Сценарий проверки — измерительный прибор этого дня.
 *
 * Устроен так, чтобы сравнение стратегий было измерением, а не впечатлением. Впечатление
 * обманывает: все три стратегии отвечают связно и уверенно, и на глаз разница между ними
 * незаметна. Заметна она только на конкретных деталях, которые прозвучали в разное время
 * и про которые в конце спрашивают прямо.
 *
 * Один и тот же файл прогоняется на всех стратегиях: сравнивать имеет смысл только
 * одинаковый вход.
 */
data class Scenario(
    val id: String,
    val title: String,
    val description: String = "",
    /** Реплики пользователя по порядку. */
    val steps: List<String>,
    /** Контрольные вопросы, которые задаются после всех реплик. */
    val checks: List<Check>,
) {
    init {
        require(steps.isNotEmpty()) { "Сценарий без реплик проверять нечего" }
        require(checks.isNotEmpty()) { "Сценарий без контрольных вопросов ничего не измеряет" }
    }
}

/**
 * Одна проверка: вопрос про деталь, которая прозвучала на шаге [plantedAtStep].
 *
 * [plantedAtStep] — не украшение отчёта, а его главная колонка. Без неё результат
 * звучит как «стратегия помнит 4 факта из 8», что не говорит ни о чём. С ней —
 * «детали с шагов 1–5 потеряны, с шага 7 и дальше на месте», то есть видно, где
 * именно проходит граница памяти.
 */
data class Check(
    val id: String,
    val plantedAtStep: Int,
    val question: String,
    /**
     * Подстроки, которые обязаны быть в ответе. Все до одной.
     *
     * Подстроки, а не точные формулировки: модель напишет «PostgreSQL 16» или
     * «постгрес» — засчитываем по корню. Сравнение без учёта регистра и с приведением
     * «ё» к «е»: «Ковалёва» и «Ковалева» — одно и то же имя, и проваливать проверку
     * из-за типографики значило бы мерить не то.
     */
    val expect: List<String>,
    /**
     * Подстроки, которых быть не должно.
     *
     * Ловит противоположную ошибку: не забывание, а выдумывание. От агента, который
     * потерял разговор, ждёшь «не помню», но чаще он уверенно достраивает правдоподобное.
     * Проверка на присутствие такого не видит вовсе.
     *
     * Жёсткое правило: сюда попадает только то, чего в разговоре **не звучало вообще**.
     * Первая версия сценария запрещала здесь `SMS` — канал, от которого на четвёртом шаге
     * сознательно отказались, — и проверка провалила безупречный ответ «email и Telegram,
     * SMS не делаем». Отвергнутый в разговоре факт законно встречается в верном ответе,
     * вместе с отрицанием, которого подстрочный поиск не видит. Поэтому запрещаем
     * `MySQL` и `WhatsApp`: их не называли ни разу, и появиться они могут только
     * из фантазии модели.
     */
    val forbid: List<String> = emptyList(),
)
