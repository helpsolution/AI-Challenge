package advent.day10.chat

import java.time.Instant

/**
 * Один факт из досье: короткая пара «ключ — значение».
 *
 * Досье — это то, чем стратегия фактов отличается от скользящего окна: оно не растёт
 * вместе с разговором и потому уходит модели целиком на каждом ходу, а окно при этом
 * остаётся тесным. Цена — лишнее обращение к модели на каждом ходу; его расход
 * записывается отдельно (см. [Upkeep]), иначе стратегия выглядела бы дешевле, чем она есть.
 *
 * [turnNumber] — ход, на котором факт записан или обновлён в последний раз. По нему видно,
 * что досье живое: значения меняются, а не только накапливаются.
 */
data class Fact(
    val key: String,
    val value: String,
    val turnNumber: Int,
    val at: Instant,
)
