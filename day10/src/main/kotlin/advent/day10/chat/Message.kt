package advent.day10.chat

import java.time.Instant

/**
 * Кто сказал. Ролей ровно две: в базе лежит только сама переписка.
 *
 * Системной инструкции здесь нет намеренно — она живёт в настройках агента и подставляется
 * при сборке промпта. Если записать её в историю, смена персоны в конфиге разошлась бы
 * с тем, что уже сохранено.
 */
enum class Role { USER, ASSISTANT }

/**
 * Одно сообщение диалога.
 *
 * В отличие от дня 8 у сообщения есть [id]: по нему ставится точка ветвления. Без
 * идентификатора «форкнуться после этого места» пришлось бы выражать через порядковый
 * номер, а он у сессии свой и после копирования перестаёт совпадать.
 */
data class Message(
    val id: Long,
    val sessionId: Long,
    val role: Role,
    val content: String,
    val at: Instant,
)
