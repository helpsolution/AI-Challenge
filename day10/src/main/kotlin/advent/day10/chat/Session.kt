package advent.day10.chat

import java.time.Instant

/**
 * Стратегия управления контекстом — то, что этот день сравнивает.
 *
 * [SLIDING_WINDOW] — модели уходят только последние N сообщений, остальное отбрасывается.
 * [FACTS] — блок ключ-значение с важными деталями плюс последние N сообщений.
 * [BRANCHING] — то же окно, но с разблокированной панелью веток.
 *
 * Почему [BRANCHING] стоит в одном ряду с двумя другими, хотя устроен иначе, написано
 * в `АРХИТЕКТУРА.md`: ветвление отвечает не на вопрос «что из истории отправить», а
 * на вопрос «какая история сейчас текущая». В хранилище это форк сессии, а не сборка
 * промпта, — поэтому в интерфейсе `ContextStrategy` его нет.
 */
enum class StrategyId { SLIDING_WINDOW, FACTS, BRANCHING }

/**
 * Один диалог со своей стратегией.
 *
 * Стратегия и её параметры записываются в сессию при создании и дальше не меняются.
 * Это главное свойство схемы: переключатель в интерфейсе создаёт **новую** сессию,
 * а не меняет режим текущей. Иначе в одной истории оказались бы ходы, часть которых
 * прошла по другим правилам, и сравнивать было бы нечего.
 *
 * Ветка — такая же сессия, у которой есть [parentId]: первые [forkedAfter] сообщений
 * родителя скопированы в неё при форке. Копия, а не ссылка — так чтение истории
 * остаётся обычным `SELECT ... WHERE session_id = ?`, одинаковым для веток и корней.
 */
data class Session(
    val id: Long,
    val title: String,
    val strategy: StrategyId,
    /** Сколько последних сообщений уходит модели дословно. Снимок настройки на момент создания. */
    val windowSize: Int,
    val createdAt: Instant,
    /** Сессия, от которой отпочковались. null — самостоятельный диалог. */
    val parentId: Long? = null,
    /** Сколько сообщений родителя скопировано в ветку. Точка ветвления. */
    val forkedAfter: Int? = null,
) {
    val isBranch: Boolean get() = parentId != null
}
