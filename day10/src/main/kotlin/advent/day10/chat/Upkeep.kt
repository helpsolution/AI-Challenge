package advent.day10.chat

import advent.day10.llm.CostSource

/**
 * Расход на обслуживание памяти: то, что стратегия потратила сверх самого ответа.
 *
 * Сущность появилась ради честности сравнения. Скользящее окно обходится одним обращением
 * к модели на ход. Стратегия фактов — двумя: вторым она обновляет досье. Запиши мы только
 * основной вызов, и таблица сравнения показала бы, что факты дешевле окна, — притом что
 * счёт от провайдера говорил бы обратное.
 *
 * Поэтому строка расхода отдельная, а не слитая с основной: «сколько стоил ответ»
 * и «сколько стоило помнить» — разные вопросы, и смысл дня как раз в их разнице.
 *
 * [error] не null означает, что обслуживание не удалось. Это не ломает ход: ответ модели
 * уже получен и сохранён, а досье просто не обновилось.
 */
data class Upkeep(
    /** Что именно делали: «досье: +2 факта, 1 обновлён». */
    val note: String,
    val latencyMs: Long,
    val promptTokens: Int? = null,
    val cachedPromptTokens: Int? = null,
    val completionTokens: Int? = null,
    val totalTokens: Int? = null,
    val costUsd: Double? = null,
    val costSource: CostSource? = null,
    val error: String? = null,
)
