package advent.day10.llm

/**
 * Ошибка обращения к LLM-провайдеру: сеть, таймаут, ответ с кодом не 2xx или пустой результат.
 *
 * Сырое тело ответа носим с собой намеренно. В этот день ошибка провайдера — не досадная
 * помеха, а главный экспонат: именно в её тексте написано, каков лимит модели и на сколько
 * мы его перебрали. Такое нельзя заменить своей формулировкой, поэтому оно доходит
 * до интерфейса дословно.
 */
class LlmException(
    message: String,
    /** Код ответа провайдера, если ответ был. */
    val providerStatus: Int? = null,
    /** Тело ответа провайдера как есть. Ключа в нём нет: ключ уходит заголовком. */
    val providerBody: String? = null,
    cause: Throwable? = null,
) : RuntimeException(message, cause)
