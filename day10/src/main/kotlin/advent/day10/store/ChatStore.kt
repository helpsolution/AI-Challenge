package advent.day10.store

import advent.day10.chat.Exchange
import advent.day10.chat.Message
import advent.day10.chat.Session
import advent.day10.chat.StrategyId
import advent.day10.chat.Turn
import advent.day10.chat.Upkeep

/**
 * Хранилище диалогов: сессии, переписка и расход по ходам.
 *
 * Единственный источник правды. Копии в памяти агента нет, поэтому «загрузить историю
 * при перезапуске» — не отдельная операция, а обычное чтение: после рестарта приложение
 * ведёт себя правильно по построению, а не потому что мы не забыли позвать загрузку.
 *
 * Три таблицы держит один контракт намеренно: удачный ход — это пара сообщений и запись
 * расхода, и записываться они обязаны вместе. Разнеси их по разным хранилищам — понадобится
 * транзакция поверх обоих, то есть ровно та связность, которую разделение обещало убрать.
 */
interface ChatStore {

    // --- сессии ---

    /** Все диалоги, новые сверху. */
    fun sessions(): List<Session>

    fun session(id: Long): Session?

    /** Требование, а не поиск: работать с несуществующей сессией нельзя. */
    fun requireSession(id: Long): Session =
        session(id) ?: throw IllegalArgumentException("Сессия $id не найдена")

    fun createSession(title: String, strategy: StrategyId, windowSize: Int): Session

    /** Ветки, отпочкованные от этой сессии. */
    fun branches(parentId: Long): List<Session>

    /**
     * Ветка от точки в диалоге: новая сессия с копией сообщений родителя по [afterMessageId]
     * включительно.
     *
     * Копия, а не ссылка на кусок родителя. Так чтение истории ветки остаётся обычным
     * `WHERE session_id = ?` — тем же запросом, что и для корневого диалога, — и весь
     * остальной код о ветвлении не знает вовсе.
     *
     * Расход родителя не копируется: ветка — новый эксперимент, и её счёт начинается
     * с нуля. Иначе сравнение веток показывало бы общее прошлое, а не то, чем они
     * отличаются.
     *
     * А вот досье фактов копируется — оно не расход, а память. Ветка обязана знать
     * то же, что знал родитель в точке отделения: иначе развилка сравнивала бы
     * не два продолжения разговора, а разговор с амнезией против разговора без неё.
     */
    fun fork(parentId: Long, afterMessageId: Long, title: String): Session

    /** Удалить диалог вместе с перепиской и расходом. Ветки удаляются отдельно. */
    fun deleteSession(id: Long)

    // --- переписка и расход ---

    /** Вся переписка сессии в порядке диалога: старое → новое. */
    fun history(sessionId: Long): List<Message>

    fun countMessages(sessionId: Long): Int

    /** Все ходы сессии, включая неудачные, в порядке номеров. */
    fun turns(sessionId: Long): List<Turn>

    /**
     * Удачный ход: вопрос, ответ и расход — одной транзакцией.
     *
     * Отсюда гарантия: в базе не может оказаться вопроса без ответа или пары сообщений
     * без их цены. «Висящий» user без assistant сбивал бы модель на следующем ходу.
     */
    fun saveTurn(sessionId: Long, question: String, answer: String, turn: Turn): Exchange

    /**
     * Расход на обслуживание памяти — уже после того, как ход записан.
     *
     * Отдельным вызовом, а не полем в [saveTurn], потому что порядок другой: стратегия
     * обновляет своё состояние после сохранения хода, и в момент записи хода этих чисел
     * ещё не существует.
     */
    fun saveUpkeep(sessionId: Long, turnNumber: Int, upkeep: Upkeep)

    /**
     * Неудачный ход: только запись расхода, переписка не меняется.
     *
     * Ход как будто не состоялся — но событие не теряется: в базе остаётся след
     * с текстом ошибки.
     */
    fun saveFailedTurn(turn: Turn)
}
