package advent.day10.store

import advent.day10.chat.Fact

/**
 * Досье стратегии фактов — узкий контракт, отдельный от [ChatStore].
 *
 * Узкий намеренно. Стратегия ведёт своё состояние сама, но за перепиской в обход агента
 * ходить не должна: история приходит к ней только через `StrategyInput`. Дай стратегии
 * весь [ChatStore] — и первая же реализация начнёт «заодно» подглядывать в чужие сессии
 * и в расход, а разобраться, что именно ушло модели, снова станет нельзя.
 *
 * Реализация у обоих контрактов одна и та же: SQL живёт в одном классе.
 */
interface FactStore {

    /** Досье сессии в порядке записи: старые факты сверху. */
    fun facts(sessionId: Long): List<Fact>

    /**
     * Применить изменения досье одной транзакцией.
     *
     * [set] заменяет значения по ключу, [remove] удаляет. Ключ уникален в пределах
     * сессии: досье — словарь, а не журнал. Повторно названный дедлайн обязан заменить
     * прежний, иначе досье растёт вместе с разговором и стратегия вырождается
     * в «отправляем всё».
     *
     * [limit] — потолок размера досье. При переполнении выбывают факты, которых дольше
     * всех не касались: если что-то не упоминалось двадцать ходов, шанс, что оно ещё
     * нужно, ниже, чем у того, что обсуждали только что. Правило грубое, но предсказуемое
     * и объяснимое — в отличие от «попросим модель сократить», где результат зависит
     * от настроения модели.
     *
     * Возвращает, сколько фактов вытеснено потолком.
     */
    fun applyFacts(
        sessionId: Long,
        set: Map<String, String>,
        remove: Collection<String>,
        turnNumber: Int,
        limit: Int,
    ): Int
}
