package advent.day9.llm

/**
 * Контракт обращения к LLM: запрос внутрь, разобранный ответ наружу.
 *
 * В этот день за контрактом стоят две реализации — [DeepSeekClient] и [OpenRouterClient].
 * Оба провайдера говорят на OpenAI-совместимой схеме, поэтому агент не знает, с кем
 * разговаривает: разница только в заголовках, ценах и том, что каждый сообщает о расходе.
 */
fun interface LlmClient {
    fun complete(request: ChatCompletionRequest): LlmCompletion
}

/** Итог одного обращения: текст ответа, кто ответил, почему остановился и во что это обошлось. */
data class LlmCompletion(
    val content: String,
    /** Скрытый ход мысли reasoning-модели. В тексте ответа его нет. */
    val reasoning: String? = null,
    val model: String? = null,
    /** Площадка, реально обслужившая запрос. Знает только агрегатор; у DeepSeek это он сам. */
    val provider: String? = null,
    val finishReason: String? = null,
    val usage: TokenUsage? = null,
)

/**
 * Расход одного обращения — в терминах приложения, а не провайдера.
 *
 * Тема дня требует три числа: сколько токенов ушло в запросе, сколько вернулось в ответе
 * и сколько это стоило. Провайдеры считают одинаково, но называют по-разному и знают
 * о деньгах разное, поэтому каждый клиент приводит свой `usage` к этому типу.
 *
 * Ключевое свойство: [promptTokens] — не наша оценка, а число, за которое провайдер
 * выставил счёт. Именно поэтому по нему можно поймать то, что иначе незаметно: если
 * история выросла, а это число нет — часть промпта до модели не дошла.
 */
data class TokenUsage(
    /** Весь вход: системная инструкция + история + новый вопрос. */
    val promptTokens: Int,
    /** Ответ модели. */
    val completionTokens: Int,
    val totalTokens: Int,
    /** Часть входа, зачтённая из кэша провайдера. Стоит в разы дешевле остального. */
    val cachedPromptTokens: Int = 0,
    /** Размышление reasoning-модели: оплачивается как выход, но в тексте ответа его нет. */
    val reasoningTokens: Int = 0,
    val costUsd: Double? = null,
    val costSource: CostSource = CostSource.UNKNOWN,
)

/**
 * Откуда взялась цена — это важно различать, а не прятать за одним числом.
 *
 * [PROVIDER] — сумма, реально списанная с аккаунта: её сообщает сам провайдер.
 * [PRICE_LIST] — наше умножение токенов на прайс из конфига. Оценка: прайс может
 * устареть, а у DeepSeek ещё и различаются пиковый и ночной тарифы.
 */
enum class CostSource { PROVIDER, PRICE_LIST, UNKNOWN }
