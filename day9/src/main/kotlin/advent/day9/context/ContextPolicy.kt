package advent.day9.context

/**
 * Как собирается контекст запроса.
 *
 * [RAW] — вся переписка уходит модели дословно, как в дни 7 и 8. Это не «выключенная
 * функция», а вторая половина эксперимента: без прогона в этом режиме сравнивать
 * не с чем.
 *
 * [SUMMARY] — последние N сообщений дословно, всё остальное одним конспектом.
 */
enum class ContextMode { RAW, SUMMARY }

/**
 * Правило сжатия: что оставить дословно, когда сворачивать и во что.
 *
 * Режим задаётся конфигом и меняется рестартом, а не переключателем в интерфейсе.
 * Причина простая: сравнивать надо два диалога, а не два состояния одного — иначе
 * в одной базе окажется перемешанная история, и «качество ответов со сжатием»
 * будет считаться по ходам, часть которых прошла без него.
 */
data class ContextPolicy(
    val mode: ContextMode,
    /** Сколько последних сообщений всегда уходят дословно. */
    val keepLast: Int,
    /** Сколько сообщений накапливается за хвостом, прежде чем свернуться в конспект. */
    val summarizeEvery: Int,
    /**
     * Потолок ответа суммаризатора. Он же — единственная жёсткая граница размера
     * конспекта: инструкция «уложись в столько-то» — просьба, а `max_tokens` — предел.
     */
    val summaryMaxTokens: Int,
    /** Модель для конспекта. Пусто — та же, что отвечает пользователю. */
    val summaryModel: String?,
) {
    init {
        require(keepLast >= 2) { "Дословно надо оставлять хотя бы одну пару вопрос-ответ (keepLast >= 2)" }
        require(summarizeEvery >= 2) { "Сворачивать пачками меньше пары сообщений бессмысленно" }
        require(summaryMaxTokens in 64..2048) { "Потолок конспекта должен быть от 64 до 2048 токенов" }
    }

    /**
     * Пора ли сворачивать.
     *
     * Условие считается по хвосту, а не по всей истории: за границей конспекта сообщений
     * может быть уже сколько угодно, и они на решение не влияют — они уже свёрнуты.
     * Сворачиваем, только когда за вычетом дословного хвоста накопилась полная пачка:
     * иначе конспект переписывался бы почти каждый ход, а его цена — обращение к модели.
     */
    fun shouldFold(tailSize: Int): Boolean =
        mode == ContextMode.SUMMARY && tailSize - keepLast >= summarizeEvery

    /**
     * Сколько символов просить у суммаризатора.
     *
     * Три символа на токен — грубая мерка для русского текста, и настоящий предел
     * всё равно ставит `max_tokens`. Число в инструкции нужно для другого: без него
     * модель пишет конспект той длины, которая ей покажется уместной, и он растёт
     * вместе с разговором — то есть ровно то, от чего мы уходим.
     */
    val summaryCharBudget: Int get() = summaryMaxTokens * 3
}
