package advent.day9.store

import advent.day9.chat.Message
import advent.day9.chat.Summary
import advent.day9.chat.Turn

/**
 * Хранилище диалога: переписка, её конспект и расход по обращениям к модели.
 *
 * Единственный источник правды. Копии в памяти агента нет, поэтому «загрузить историю
 * при перезапуске» — не отдельная операция, а обычное чтение: после рестарта приложение
 * ведёт себя правильно по построению, а не потому что мы не забыли позвать загрузку.
 *
 * Ключевое для этого дня: [history] по-прежнему хранит **всю** переписку целиком, а конспект
 * только добавляется рядом. Сжатие происходит на пути к модели, а не в базе. Отсюда два
 * следствия. Первое: режим RAW воспроизводим из той же базы в любой момент — иначе
 * сравнивать «до и после» было бы нечем. Второе: сжатие ничего не удаляет, поэтому
 * неудачный конспект — не потеря данных.
 */
interface ChatStore {

    /** Вся переписка в порядке диалога: старое → новое. С номерами: конспекту нужны границы. */
    fun history(): List<Message>

    /** Сообщения после указанного номера — дословный хвост за границей конспекта. */
    fun messagesAfter(messageId: Long): List<Message>

    /** Сколько сообщений сохранено. */
    fun count(): Int

    /**
     * Символов во всей переписке.
     *
     * Отдельный запрос, а не длина [history]: в режиме SUMMARY всю историю мы намеренно
     * не читаем, а знать её размер надо — с ним сравнивается то, что реально ушло модели.
     */
    fun chars(): Int

    /** Все измеренные обращения к модели, включая неудачные и сворачивания, в хронологии. */
    fun turns(): List<Turn>

    /** Актуальный конспект — версия с наибольшим номером. null, если история ещё не сворачивалась. */
    fun latestSummary(): Summary?

    /** Все версии конспекта: по ним видно, как пересказ пересказа теряет подробности. */
    fun summaries(): List<Summary>

    /**
     * Удачный ход: вопрос, ответ и расход — одной транзакцией.
     *
     * Отсюда гарантия: в базе не может оказаться вопроса без ответа или пары сообщений
     * без их цены. «Висящий» user без assistant сбивал бы модель на следующем ходу.
     */
    fun saveTurn(question: Message, answer: Message, turn: Turn)

    /**
     * Неудачное обращение: только запись расхода, переписка не меняется.
     *
     * Так сохраняется правило дня 7 — неудачный ход не попадает в историю, — но само
     * событие не теряется: в базе остаётся след с текстом ошибки.
     */
    fun saveFailedTurn(turn: Turn)

    /**
     * Новая версия конспекта и её цена — одной транзакцией.
     *
     * Вместе по той же причине, что вопрос с ответом: конспект без записи о расходе
     * означал бы бесплатное сжатие, а запись без конспекта — плату ни за что.
     */
    fun saveSummary(summary: Summary, turn: Turn)

    /** Забыть всё: переписку, конспекты и расход. */
    fun clear()
}
