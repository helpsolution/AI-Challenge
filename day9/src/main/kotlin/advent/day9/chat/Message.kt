package advent.day9.chat

import java.time.Instant

/**
 * Кто сказал. Ролей ровно две: в базе лежит только сама переписка.
 *
 * Системной инструкции здесь нет намеренно — она живёт в настройках агента и подставляется
 * при сборке запроса. Если записать её в историю, смена персоны в конфиге разошлась бы
 * с тем, что уже сохранено. По той же причине здесь нет и конспекта: он не чья-то реплика,
 * а производное от них, и у него своя таблица.
 */
enum class Role { USER, ASSISTANT }

/** Одно сообщение диалога — то, что хранится и то, что уходит модели. */
data class Message(
    val role: Role,
    val content: String,
    val at: Instant,
    /**
     * Номер в базе. У ещё не сохранённого сообщения его нет.
     *
     * В этот день он перестаёт быть деталью хранения и становится частью предметной
     * области: конспект обязан назвать границу — до какого сообщения он досчитан.
     * Без такой границы «хвост из последних N» и «остальное в summary» не сходятся:
     * непонятно, что именно уже свёрнуто, а что модель всё ещё видит дословно.
     */
    val id: Long? = null,
)
