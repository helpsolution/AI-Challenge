package advent.day9.chat

import java.time.Instant

/**
 * Конспект начала разговора — главная новая сущность дня.
 *
 * Смысл в подмене: старые сообщения перестают уходить модели дословно, вместо них уходит
 * один короткий текст. Поэтому конспект — не украшение истории, а её замена, и всё, чего
 * в нём нет, для модели больше не существует. Отсюда и требование задания хранить его
 * отдельно: у него своя жизнь, своя цена и своя граница в переписке.
 *
 * Версии не перезаписывают друг друга, а накапливаются: каждая следующая складывается
 * из предыдущей и новой пачки сообщений ([foldedMessages]), поэтому потеря деталей
 * копится, и увидеть это можно только сравнив версии между собой. В промпт идёт последняя,
 * в базе остаются все.
 *
 * Цены своего создания здесь нет: сжатие — это обращение к модели, и его расход лежит там,
 * где расход всех обращений, — в таблице `turn` с [Turn.kind] = SUMMARY. Иначе экономия
 * считалась бы по одной половине счёта.
 */
data class Summary(
    val version: Int,
    val at: Instant,
    /** Первое сообщение, попавшее в конспект. У первой версии — самое начало диалога. */
    val coversFromMessageId: Long,
    /** Последнее свёрнутое сообщение. Всё, что дальше, модель видит дословно. */
    val coversUptoMessageId: Long,
    /** Сколько сообщений добавила именно эта версия. */
    val foldedMessages: Int,
    /** Сколько сообщений всего осталось за границей конспекта. */
    val coveredMessages: Int,
    val content: String,
    /** После какого хода составлен. Цена того же хода лежит в `turn` с kind = SUMMARY. */
    val turnNumber: Int,
) {
    val chars: Int get() = content.length
}
