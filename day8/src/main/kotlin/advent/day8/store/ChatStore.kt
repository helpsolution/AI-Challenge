package advent.day8.store

import advent.day8.chat.Message
import advent.day8.chat.Turn

/**
 * Хранилище диалога: переписка и расход по ходам.
 *
 * Единственный источник правды. Копии в памяти агента нет, поэтому «загрузить историю
 * при перезапуске» — не отдельная операция, а обычное чтение: после рестарта приложение
 * ведёт себя правильно по построению, а не потому что мы не забыли позвать загрузку.
 * В этот день то же свойство распространяется на расход — график роста токенов и цены
 * тоже переживает перезапуск.
 *
 * Две таблицы держит один контракт намеренно: удачный ход — это пара сообщений и запись
 * расхода, и записываться они обязаны вместе. Разнеси их по двум хранилищам — и понадобится
 * транзакция поверх обоих, то есть ровно та связность, которую разделение обещало убрать.
 */
interface ChatStore {

    /** Вся переписка в порядке диалога: старое → новое. */
    fun history(): List<Message>

    /** Сколько сообщений сохранено. */
    fun count(): Int

    /** Все измеренные ходы, включая неудачные, в порядке номеров. */
    fun turns(): List<Turn>

    /**
     * Удачный ход: вопрос, ответ и расход — одной транзакцией.
     *
     * Отсюда гарантия: в базе не может оказаться вопроса без ответа или пары сообщений
     * без их цены. «Висящий» user без assistant сбивал бы модель на следующем ходу.
     */
    fun saveTurn(question: Message, answer: Message, turn: Turn)

    /**
     * Неудачный ход: только запись расхода, переписка не меняется.
     *
     * Так сохраняется правило дня 7 — неудачный ход не попадает в историю, — но само
     * событие не теряется: в базе остаётся след с текстом ошибки.
     */
    fun saveFailedTurn(turn: Turn)

    /** Забыть всё: и переписку, и её цену. */
    fun clear()
}
