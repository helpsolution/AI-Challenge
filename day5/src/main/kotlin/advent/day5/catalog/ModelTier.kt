package advent.day5.catalog

/**
 * Три уровня, между которыми задание просит увидеть разницу.
 *
 * Граница между уровнями — не формальная величина вроде числа параметров: у закрытых
 * моделей его никто не публикует. Уровень здесь означает класс задач, на который
 * модель рассчитана, а цена служит его косвенным, зато честным подтверждением —
 * между слабым и сильным уровнем она отличается примерно в сто раз.
 */
enum class ModelTier(
    val title: String,
    val emoji: String,
    val summary: String,
    /** Что от уровня разумно ждать — и чего ждать не стоит. */
    val goodFor: List<String>,
    val weakAt: List<String>,
) {
    WEAK(
        title = "Слабая",
        emoji = "🪫",
        summary = "Единицы миллиардов параметров, помещается на одну видеокарту. " +
            "Отвечает почти мгновенно и стоит копейки.",
        goodFor = listOf("классификация", "извлечение полей", "простые переформулировки"),
        weakAt = listOf("многошаговые рассуждения", "точный счёт", "соблюдение формата"),
    ),
    MEDIUM(
        title = "Средняя",
        emoji = "⚡",
        summary = "Рабочая лошадка: держит инструкции и формат, справляется с обычными " +
            "задачами и остаётся дешёвой при потоке.",
        goodFor = listOf("тексты", "код по образцу", "структурированный вывод"),
        weakAt = listOf("длинные цепочки логики", "редкие предметные области"),
    ),
    STRONG(
        title = "Сильная",
        emoji = "🚀",
        summary = "Флагман. Рассуждает по шагам, ловит подвох в условии — и стоит " +
            "на два порядка дороже слабой.",
        goodFor = listOf("логика и математика", "сложный код", "разбор неоднозначных условий"),
        weakAt = listOf("массовые дешёвые операции", "задачи, где важна задержка"),
    ),
}
