                "Выпиши слово по буквам с номерами, потом дай ответ числом.",
        ),
        Preset(
            id = "multistep",
            title = "Несколько шагов подряд",
            hint = "Четыре действия, где ошибка на любом шаге ломает ответ целиком.",
            prompt = "В магазин привезли 12 ящиков по 18 бутылок. Шесть бутылок разбились. " +
