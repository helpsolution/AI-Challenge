package advent.day3.reasoning

import org.springframework.stereotype.Component

/**
 * Тексты инструкций для каждого способа. Вынесены в отдельный класс, потому что
 * это и есть предмет дня 3: сравниваются не модели и не параметры, а формулировки.
 *
 * Все промпты показываются в интерфейсе целиком — иначе сравнение способов
 * пришлось бы принимать на веру.
 */
@Component
class TechniquePrompts {

    /**
     * Системная инструкция способа. У прямого ответа её нет вовсе — в этом весь смысл способа.
     *
     * [answerMarker] — общая для всех способов добавка: требование закончить строкой
     * «ОТВЕТ: …». Она нужна, чтобы финальные ответы можно было сопоставить между собой,
     * и включается отдельным переключателем. `null` — не добавлять.
     */
    fun systemPrompt(technique: Technique, answerMarker: String?): String? {
        val base = when (technique) {
            Technique.DIRECT -> null
            Technique.STEP_BY_STEP -> STEP_BY_STEP
            Technique.META_PROMPT -> null // у второго вызова инструкцию заменяет промпт от модели
            Technique.EXPERT_PANEL -> EXPERT_PANEL
        }
        return join(base, answerLine(answerMarker))
    }

    /** Инструкция первого вызова мета-промпта: написать промпт, но не решать задачу. */
    fun metaAuthorPrompt(): String = META_AUTHOR

    /** Требование закончить ответ строкой с маркером — единственная добавка, общая для всех способов. */
    fun answerLine(marker: String?): String? {
        val m = marker?.trim()?.takeIf { it.isNotEmpty() } ?: return null
        return "Последней строкой ответа напиши ровно: «$m <ответ>», где <ответ> — только сам ответ (число, слово или короткая фраза), без пояснений и без повторения условия."
    }

    private fun join(vararg parts: String?): String? =
        parts.filterNotNull().filter { it.isNotBlank() }.takeIf { it.isNotEmpty() }?.joinToString("\n\n")

    private companion object {
        val STEP_BY_STEP = """
            Решай задачу пошагово.
            Разбей решение на пронумерованные шаги. В каждом шаге выполняй ровно одно действие
            и показывай его промежуточный результат. Не переходи к следующему шагу, пока не закончен предыдущий.
            В конце подставь полученный результат обратно в условие и проверь, что он ему не противоречит.
        """.trimIndent()

        val META_AUTHOR = """
            Ты — инженер по промптам. Сейчас тебе дадут задачу. Решать её не нужно.
            Составь промпт, по которому языковая модель решит эту задачу максимально точно.
            Укажи в нём подходящую роль, метод рассуждения, на что обратить внимание в условии
            и какие ловушки в нём есть, а также в каком виде выдать ответ.
            Промпт должен быть самодостаточным: включи в него полный текст задачи.
            Верни только текст промпта — без заголовков, пояснений и кавычек вокруг.
        """.trimIndent()

        val EXPERT_PANEL = """
            Задачу разбирает группа из трёх экспертов. Отыграй каждого по очереди, не смешивая их голоса.
            Каждый эксперт даёт собственное решение, даже если оно совпадает с предыдущим.

            Аналитик — разбирает условие: что дано, что именно спрашивается, где формулировка двусмысленна.
            Инженер — считает и решает по шагам, перепроверяя каждое вычисление.
            Критик — ищет ошибки в решениях аналитика и инженера, проверяет крайние случаи и типичные ловушки.

            Затем подведи итог: сведи три мнения, объясни расхождения, если они есть,
            и дай окончательный ответ.

            Формат ответа:
            ### Аналитик
            ### Инженер
            ### Критик
            ### Итог
        """.trimIndent()
    }
}
