package advent.day3.reasoning

/**
 * Четыре способа заставить модель рассуждать над одной и той же задачей.
 * Отличаются они только тем, что уходит в system-prompt и сколько вызовов делается —
 * ни задача, ни модель, ни температура между способами не меняются.
 */
enum class Technique(
    val title: String,
    val summary: String,
    /** Сколько раз способ ходит в API. Показывается в интерфейсе до запуска. */
    val calls: Int,
) {
    DIRECT(
        title = "Прямой ответ",
        summary = "Задача уходит как есть. Ни роли, ни метода, ни требования рассуждать.",
        calls = 1,
    ),
    STEP_BY_STEP(
        title = "Пошаговое решение",
        summary = "Та же задача плюс инструкция разбить решение на шаги и проверить результат.",
        calls = 1,
    ),
    META_PROMPT(
        title = "Промпт от самой модели",
        summary = "Сначала модель пишет промпт для решения задачи, затем этим промптом её и решает.",
        calls = 2,
    ),
    EXPERT_PANEL(
        title = "Группа экспертов",
        summary = "Один вызов, в котором модель отыгрывает аналитика, инженера и критика, а потом сводит итог.",
        calls = 1,
    ),
}
