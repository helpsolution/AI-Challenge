package advent.day7.store

import advent.day7.chat.Message

/**
 * Хранилище переписки. Единственный источник правды о диалоге: копии в памяти агента нет,
 * поэтому «загрузить историю при перезапуске» не отдельная операция, а обычное чтение —
 * после рестарта приложение ведёт себя правильно по построению, а не потому что мы
 * не забыли позвать загрузку.
 */
interface MessageStore {

    /** Вся переписка в порядке диалога: старое → новое. */
    fun history(): List<Message>

    /**
     * Вопрос и ответ пишутся вместе, одной транзакцией.
     *
     * Неудачный ход в историю не попадает: пишем только после ответа модели. Поэтому пара
     * либо есть целиком, либо её нет — «висящего» вопроса без ответа в контексте не будет.
     */
    fun append(question: Message, answer: Message)

    /** Забыть всё. */
    fun clear()

    /** Сколько сообщений сохранено. Интерфейсу — чтобы показать, что история именно на диске. */
    fun count(): Int
}
