package advent.day7.chat

import java.time.Instant

/**
 * Кто сказал. Ролей ровно две: в базе лежит только сама переписка.
 *
 * Системной инструкции здесь нет намеренно — она живёт в настройках агента и подставляется
 * при сборке запроса. Если записать её в историю, смена персоны в конфиге разошлась бы
 * с тем, что уже сохранено.
 */
enum class Role { USER, ASSISTANT }

/** Одно сообщение диалога — то, что хранится и то, что уходит модели. */
data class Message(
    val role: Role,
    val content: String,
    val at: Instant,
)
