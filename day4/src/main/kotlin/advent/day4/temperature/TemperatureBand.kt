package advent.day4.temperature

/**
 * Диапазоны температуры и то, для чего каждый из них годится.
 *
 * Это и есть вывод дня 4, вынесенный в код: интерфейс строит по нему справочник,
 * а не дублирует рекомендации у себя в разметке. Границы условные — провайдер
 * никаких порогов не декларирует, ступеньки в поведении модели нет,
 * есть плавный рост разброса.
 */
enum class TemperatureBand(
    val title: String,
    val emoji: String,
    val range: String,
    val summary: String,
    /** Задачи, где этот диапазон уместен. */
    val bestFor: List<String>,
    /** Задачи, где он же вредит. */
    val avoidFor: List<String>,
    /** Верхняя граница диапазона включительно. */
    val upperBound: Double,
) {
    COLD(
        title = "Точность",
        emoji = "🧊",
        range = "0.0 – 0.3",
        summary = "Модель почти всегда выбирает самое вероятное продолжение. " +
            "Ответы от прогона к прогону совпадают или расходятся в мелочах.",
        bestFor = listOf(
            "извлечение данных из текста",
            "JSON и другие машиночитаемые форматы",
            "арифметика и логика",
            "код и SQL",
            "перевод и классификация",
        ),
        avoidFor = listOf("тексты для людей — выходят сухими и шаблонными", "подбор вариантов и идей"),
        upperBound = 0.3,
    ),
    WARM(
        title = "Баланс",
        emoji = "🌤",
        range = "0.4 – 0.9",
        summary = "Смысл держится, формулировки живые. Компромисс по умолчанию, " +
            "если задача не про точность и не про идеи.",
        bestFor = listOf(
            "деловая переписка",
            "описания товаров",
            "объяснения и обучающие тексты",
            "чат-ассистент",
            "пересказ и редактура",
        ),
        avoidFor = listOf("ответы, которые сравниваются между прогонами", "строгие форматы"),
        upperBound = 0.9,
    ),
    HOT(
        title = "Креатив",
        emoji = "🔥",
        range = "1.0 – 1.5",
        summary = "Модель охотно берёт менее вероятные слова. Разброс между прогонами " +
            "заметный — это и нужно, когда вариантов должно быть много.",
        bestFor = listOf(
            "слоганы, названия, заголовки",
            "мозговой штурм",
            "художественный текст",
            "нестандартные ходы в сценарии",
        ),
        avoidFor = listOf("факты и числа — начинают плыть", "любые задачи с одним правильным ответом"),
        upperBound = 1.5,
    ),
    SCALDING(
        title = "Перегрев",
        emoji = "🌋",
        range = "1.6 – 2.0",
        summary = "За пределом полезного: связность рвётся, появляются несуществующие слова " +
            "и обрывы на полуфразе. Показан здесь, чтобы было видно, где заканчивается креатив.",
        bestFor = listOf("демонстрация того, как ломается генерация"),
        avoidFor = listOf("любые прикладные задачи"),
        upperBound = 2.0,
    ),
    ;

    companion object {
        fun of(temperature: Double): TemperatureBand =
            entries.firstOrNull { temperature <= it.upperBound } ?: SCALDING
    }
}
