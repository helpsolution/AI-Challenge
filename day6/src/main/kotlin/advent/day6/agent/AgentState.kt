package advent.day6.agent

/**
 * Чем агент занят прямо сейчас. THINKING — запрос ушёл, первого токена ещё нет;
 * ANSWERING — текст течёт; IDLE — свободен и ждёт.
 */
enum class AgentState { IDLE, THINKING, ANSWERING }

/**
 * Настроение агента. Оно не выдумывается и не спрашивается у модели — оно выводится
 * из измеримых сигналов: занятости, тишины в диалоге, скорости последнего ответа, сбоев.
 * Интерфейс по нему анимирует аватар, поэтому каждое значение имеет наблюдаемую причину.
 */
enum class Mood {
    /** Ни одного хода ещё не было или диалог давно молчит. */
    SLEEPY,
    /** Запрос получен, ответ ещё не начался. */
    CURIOUS,
    /** Ответ идёт. */
    CHATTY,
    /** Последний ход закончился сбоем. */
    GRUMPY,
    /** Последний ответ дался тяжело — дольше порога. */
    TIRED,
    /** Всё в порядке. */
    CONTENT,
}
